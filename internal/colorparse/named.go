// ParseNamed looks up a case-insensitive W3C color keyword. Unknown
// names yield ErrUnknown.
func ParseNamed(s string) (Color, error) {
	c, ok := named[strings.ToLower(strings.TrimSpace(s))]
	if !ok {
		return Color{}, fmt.Errorf("%w: %q", ErrUnknown, s)
	}
	return c, nil
}
